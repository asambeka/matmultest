// Operand specification and the row generator.
//
// An operand is fully described by its OperandSpec: the same spec always
// generates the same bytes, for any row range, thread count or machine.
#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "json.hpp"

namespace mg {

constexpr int kAlgoVersion = 1;  // bump whenever generated bytes would change
constexpr const char* kToolVersion = "matgen 0.1.0";

enum class DType { F16, BF16, F8E4M3, F8E5M2, I8, I4 };
enum class Dist { Normal, LaplaceOutlier, UniformInt };
enum class Scale { None, Tensor, Row, Group };

const char* dtype_name(DType d);
bool parse_dtype(const std::string& s, DType& d);
const char* dist_name(Dist d);
const char* scale_name(Scale s);

// Random streams (third Philox counter word).
constexpr uint32_t kStreamValues = 0;
constexpr uint32_t kStreamOutlierCols = 1;

struct OperandSpec {
    std::string id, cls, role;
    int64_t rows = 0, cols = 0;
    DType dtype = DType::F16;
    Dist dist = Dist::Normal;
    Scale scale = Scale::None;
    float stddev = 1.0f;
    float outlier_frac = 0.0f, outlier_mult = 1.0f;
    int32_t group_size = 0;
    float tensor_scale = 1.0f;  // real value = stored value * tensor_scale
    uint64_t seed = 0, key = 0;

    // Storage and integrity
    bool stored = false;
    int64_t tile_rows = 0;
    std::vector<uint64_t> tile_hash;  // XXH64 of each tile's data bytes
    uint64_t scales_hash = 0;         // XXH64 of the whole scales array

    // Measured statistics of the source (pre-encoding) values
    double stat_min = 0, stat_max = 0, stat_mean = 0, stat_std = 0;

    size_t row_bytes() const;
    size_t scales_per_row() const;  // floats per row in the scales array
    int64_t data_bytes() const { return rows * (int64_t)row_bytes(); }
    int64_t scales_bytes() const { return rows * (int64_t)scales_per_row() * 4; }
    int64_t elements() const { return rows * cols; }
    int64_t num_tiles() const { return tile_rows ? (rows + tile_rows - 1) / tile_rows : 0; }

    // Fills derived fields (key, tensor_scale, tile_rows) and validates.
    void finalize();
};

struct Stats {
    double sum = 0, sum2 = 0;
    double mn = 1e300, mx = -1e300;
    int64_t n = 0;
    void merge(const Stats& o) {
        sum += o.sum; sum2 += o.sum2; n += o.n;
        if (o.mn < mn) mn = o.mn;
        if (o.mx > mx) mx = o.mx;
    }
};

uint64_t derive_key(uint64_t seed, const std::string& id);

// Generates rows [row0, row0+nrows) into data (nrows * row_bytes bytes) and,
// if the operand has row or group scales, scales (nrows * scales_per_row floats).
void generate_rows(const OperandSpec& s, int64_t row0, int64_t nrows, uint8_t* data,
                   float* scales, Stats* stats = nullptr);

// Same, split across threads (nthreads <= 0: all hardware threads).
void generate_rows_parallel(const OperandSpec& s, int64_t row0, int64_t nrows, uint8_t* data,
                            float* scales, int nthreads, Stats* stats = nullptr);

int default_threads();

Json spec_to_json(const OperandSpec& s);
OperandSpec spec_from_json(const Json& j);

std::string hex64(uint64_t v);
uint64_t parse_hex64(const std::string& s);

}  // namespace mg
